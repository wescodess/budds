export const permittedSourceLength = 60_000

export const fill = (unit: string, length: number, prefix = '', suffix = '') => {
  const room = Math.max(0, length - prefix.length - suffix.length)
  return `${prefix}${unit.repeat(Math.ceil(room / unit.length)).slice(0, room)}${suffix}`
}

